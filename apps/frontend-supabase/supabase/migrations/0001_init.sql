create policy "matches_public_read" on public.matches
  for select using (true);

create policy "match_judges_public_read" on public.match_judges
  for select using (true);

-- NOTE: политики INSERT/UPDATE/DELETE намеренно отсутствуют для anon/authenticated.
-- Все мутации выполняются с service_role ключом (bypass RLS) в Server Actions,
-- где роли проверяются серверным кодом (см. app/lib/permissions.ts).

-- ============================================================================
-- RPC: can_user_judge_match — может ли пользователь судить матч.
-- Замена TournamentsService.assertCanJudgeMatch одним SQL-запросом.
-- Возвращает true для admin; для referee — если он в tournament_referees
-- турнира этого матча (match → group → tournament → referees).
-- ============================================================================
create or replace function public.can_user_judge_match(p_match_id bigint, p_user_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.matches m
    join public.groups g               on g.id = m.group_id
    join public.tournaments t          on t.id = g.tournament_id
    join public.tournament_referees tr on tr.tournament_id = t.id
    where m.id = p_match_id
      and tr.user_id = p_user_id
  )
    or exists (
      -- admin судит любой матч
      select 1 from public.profiles
      where id = p_user_id and role = 'admin'
    );
$$;

comment on function public.can_user_judge_match is 'Может ли пользователь судить матч (admin — всегда; referee — если он в судьях турнира)';

-- ============================================================================
-- Storage: bucket для аватаров игроков (публичное чтение).
-- Замена player_photos/ как статики в NestJS.
-- ============================================================================
insert into storage.buckets (id, name, public)
values ('player-avatars', 'player-avatars', true)
on conflict (id) do nothing;

-- Политика: запись только авторизованным (RLS Storage). Чтение публичное (bucket public=true).
create policy "player_avatars_public_read" on storage.objects
  for select using (bucket_id = 'player-avatars');

create policy "player_avatars_authed_write" on storage.objects
  for insert to authenticated with check (bucket_id = 'player-avatars');

create policy "player_avatars_authed_update" on storage.objects
  for update to authenticated using (bucket_id = 'player-avatars');

create policy "player_avatars_authed_delete" on storage.objects
  for delete to authenticated using (bucket_id = 'player-avatars');

